import { test, expect } from '@playwright/test'

test('create a workspace, handle a ticket, approve a draft, and review audit history', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Create an account', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`browser-${Date.now()}@example.com`)
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password-42')
  await page.getByLabel('Workspace name').fill('Acceptance workspace')
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'inbox', exact: true })).toBeVisible()
  await expect(page.getByText('No tickets found.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'inbox', exact: true })).toBeVisible()
  await page.getByLabel('Subject', { exact: true }).fill('Track order 42')
  await page.getByLabel('Customer email').fill('customer@example.com')
  await page.getByLabel('Message', { exact: true }).fill('Where is my shipment?')
  await page.getByRole('button', { name: 'Create ticket', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Track order 42' })).toBeVisible()
  await page.getByLabel('Attach PDF, text or image (up to 5 MB)').setInputFiles({ name: 'receipt.txt', mimeType: 'text/plain', buffer: Buffer.from('Browser acceptance receipt') })
  await page.getByRole('button', { name: 'Upload file', exact: true }).click()
  const attachment = page.getByRole('link', { name: 'receipt.txt', exact: true })
  await expect(attachment).toBeVisible()
  const downloaded = await page.request.get((await attachment.getAttribute('href'))!)
  expect(downloaded.status()).toBe(200)
  expect(await downloaded.text()).toBe('Browser acceptance receipt')
  await page.getByLabel('Internal note').fill('Checking with fulfillment team')
  await page.getByRole('button', { name: 'Add note', exact: true }).click()
  await expect(page.getByText('Checking with fulfillment team', { exact: true })).toBeVisible()
  await page.getByLabel('Response draft', { exact: true }).fill('We are investigating the shipment.')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Approve saved draft' })).toBeEnabled()
  await page.getByRole('button', { name: 'Approve saved draft' }).click()
  await expect(page.getByText('Version 1 approved. Approval does not send email.')).toBeVisible()
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  }
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: 'test-results/workspace-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'activity', exact: true }).click()
  await expect(page.getByText(/draft.approved/)).toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

